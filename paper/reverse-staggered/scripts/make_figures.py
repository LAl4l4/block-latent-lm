"""Generate the figures and data tables for the reverse-staggered paper.

Inputs (local only, gitignored):
  runs/schedule-mask/summary.md       3-seed, 5000-step study
  runs/schedule-mask-long/summary.md  seed 42, 20000 steps
  runs/schedule-mask{,-tradeoff}/<arm>-s42/final.json  speed/quality sweep

The per-slot CE lines and the sweep costs are copied to data/*.csv, so the
paper still builds when runs/ is absent: in that case the script reads the CSV
files back instead. Outputs are pgfplots/TikZ
sources that main.tex \\input's, so no plotting library is needed.

Usage (from the repository root):
  D:\\Code\\venv313\\Scripts\\python.exe paper/reverse-staggered/scripts/make_figures.py
"""

import csv
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent.parent
DATA, FIGURES = HERE / "data", HERE / "figures"

SOURCES = {
    "5k": ROOT / "runs/schedule-mask/summary.md",
    "20k": ROOT / "runs/schedule-mask-long/summary.md",
}
# (run name, legend label, colour, mark). Colours are the first four slots of a
# validated categorical palette; causal is a neutral dashed reference.
SERIES = [
    ("causal", "causal", "black!55", "none"),
    ("forward8", "forward-8", "cOrange", "triangle*"),
    ("reverse16", "reverse-16", "cAqua", "diamond*"),
    ("reverse16g8", "reverse-16-g8", "cYellow", "square*"),
    ("reverse8g8", "reverse-8-g8", "cBlue", "*"),
]
L = 16
# Speed/quality sweep: (series, legend label, colour, mark, [(arm, tokens/step)]).
# Tokens/step is measured over the 7 generated blocks of a window.
TRADEOFF = [
    ("forward", "forward-$s$", "cOrange", "triangle*",
     [("forward8", 1.75), ("forward4", 2.8), ("forward2", 4.0), ("forward1", 5.09), ("forward0", 7.0)]),
    ("token", "token reversal ($g=1$)", "cAqua", "diamond*",
     [("reverse8", 1.75), ("reverse4", 2.8), ("reverse2", 4.0), ("reverse1", 5.09), ("reverse0", 7.0)]),
    ("segment", "segment reversal ($g=s$)", "cBlue", "*",
     [("reverse8g8", 1.75), ("reverse4g4", 2.8), ("reverse2g2", 4.0)]),
]
TRADEOFF_ROOTS = [ROOT / "runs/schedule-mask-tradeoff", ROOT / "runs/schedule-mask"]


def parse_summary(path):
    """Return {run: [16 per-slot CE values]} from a seam.summarize table."""
    rows = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"- (\w+): ((?:[\d.]+ ?){16})$", line.strip())
        if match:
            rows[match.group(1)] = [float(x) for x in match.group(2).split()]
    return rows


def load(tag):
    csv_path = DATA / f"per_slot_ce_{tag}.csv"
    names = [name for name, *_ in SERIES]
    if SOURCES[tag].exists():
        rows = parse_summary(SOURCES[tag])
        missing = [n for n in names if n not in rows]
        if missing:
            raise KeyError(f"{SOURCES[tag]} lacks per-slot rows for {missing}")
        DATA.mkdir(exist_ok=True)
        with csv_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(["slot", *names])
            for j in range(L):
                writer.writerow([j + 1, *(f"{rows[n][j]:.2f}" for n in names)])
        return {n: rows[n] for n in names}
    with csv_path.open(encoding="utf-8") as f:
        table = list(csv.DictReader(f))
    return {n: [float(r[n]) for r in table] for n in names}


def per_slot_figure(panels):
    """Two-panel pgfplots figure: per-slot steady-state CE at 5k and 20k steps."""
    out = [
        "% Generated by scripts/make_figures.py -- do not edit by hand.",
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=2 by 1, horizontal sep=1.4cm},",
        "  width=0.5\\textwidth, height=5.2cm, xmin=0.5, xmax=16.5, ymin=0.6, ymax=5.8,",
        "  xtick={1,4,8,9,12,16}, ytick={1,2,3,4,5},",
        "  xlabel={in-block slot $j+1$ (text position)}, ylabel={CE (nats)},",
        "  grid=major, grid style={black!10}, axis line style={black!40},",
        "  tick style={black!40}, label style={font=\\small}, tick label style={font=\\footnotesize},",
        "  title style={font=\\small}, every axis plot/.append style={line width=1pt, mark size=1.6pt},",
        "  legend style={font=\\footnotesize, draw=black!20,",
        "    legend columns=5, /tikz/every even column/.append style={column sep=6pt}}]",
    ]
    titles = {"5k": "5k steps, 3 seeds (mean)", "20k": "20k steps, seed 42"}
    for index, (tag, rows) in enumerate(panels.items()):
        out.append(f"\\nextgroupplot[title={{{titles[tag]}}}"
                   + ("" if index == 0 else ", ylabel={}, yticklabels={}, legend to name=slotlegend")
                   + "]")
        # Segment boundary for g = 8: the right half (slots 9-16) is written first.
        out.append("\\draw[black!35, dotted, line width=0.8pt] (axis cs:8.5,0.6) -- (axis cs:8.5,5.8);")
        for name, label, colour, mark in SERIES:
            style = f"color={colour}, mark={mark}"
            if name == "causal":
                style += ", dashed"
            coords = " ".join(f"({j + 1},{v:.2f})" for j, v in enumerate(rows[name]))
            out.append(f"\\addplot[{style}] coordinates {{{coords}}};")
            if index == 1:
                out.append(f"\\addlegendentry{{{label}}}")
    # One shared legend under both panels (\ref needs a second LaTeX pass).
    out += ["\\end{groupplot}", "\\end{tikzpicture}", "", "\\par\\smallskip\\ref{slotlegend}", ""]
    return "\n".join(out)


def clock(schedule, t, j, s, g=1):
    """Generation time of slot j (0-based) in block t; matches visibility()."""
    if schedule == "forward":
        return s * t + j
    if schedule == "meet":
        # Pairs of blocks: even block forward, odd block reversed and s steps late.
        start = (t // 2) * (L + s) + (t % 2) * s
        return start + (j if t % 2 == 0 else L - 1 - j)
    q, r = divmod(j, g)
    return s * t + (L // g - 1 - q) * g + r


def schedule_figure(blocks=3):
    """Grid of generation times for three blocks under four seam-last schedules."""
    rows = [
        ("forward-8", "forward", 8, 1),
        ("reverse-8", "reverse", 8, 1),
        ("reverse-8-g8", "reverse", 8, 8),
        ("meet-1", "meet", 1, 1),
    ]
    w, h = 0.27, 0.40
    top = max(clock(k, t, j, s, g) for _, k, s, g in rows for t in range(blocks) for j in range(L))
    out = [
        "% Generated by scripts/make_figures.py -- do not edit by hand.",
        "\\begin{tikzpicture}[x=1cm, y=1cm, font=\\tiny]",
    ]
    for row, (label, kind, s, g) in enumerate(rows):
        y = -row * (h + 0.32)
        out.append(f"\\node[anchor=east, font=\\footnotesize] at (-0.1,{y + h / 2:.2f}) {{{label}}};")
        for t in range(blocks):
            for j in range(L):
                tau = clock(kind, t, j, s, g)
                x = (t * L + j) * w + t * 0.12
                shade = 8 + round(62 * tau / top)
                out.append(
                    f"\\draw[fill=cBlue!{shade}, draw=white, line width=0.4pt] "
                    f"({x:.2f},{y:.2f}) rectangle ++({w:.2f},{h:.2f}) "
                    f"node[pos=0.5, text={'white' if shade > 45 else 'black'}] {{{tau}}};"
                )
        # Seam: last token of block 0 and first token of block 1.
        last, first = clock(kind, 0, L - 1, s, g), clock(kind, 1, 0, s, g)
        x0 = (L - 1) * w
        x1 = L * w + 0.12
        colour = "cOrange" if first <= last else "black!70"
        out.append(
            f"\\draw[{colour}, line width=1.1pt] ({x0:.2f},{y:.2f}) rectangle ++({w:.2f},{h:.2f});"
            f"\\draw[{colour}, line width=1.1pt] ({x1:.2f},{y:.2f}) rectangle ++({w:.2f},{h:.2f});"
        )
        verdict = "seam dropped (distance 1)" if first <= last else "seam visible"
        out.append(
            f"\\node[anchor=west, font=\\scriptsize, text=black!75] at "
            f"({blocks * L * w + blocks * 0.12:.2f},{y + h / 2:.2f}) {{{verdict}}};"
        )
    for t in range(blocks):
        x = (t * L + L / 2) * w + t * 0.12
        out.append(f"\\node[font=\\scriptsize] at ({x:.2f},{h + 0.18:.2f}) {{block $t{'' if t == 1 else ('-1' if t == 0 else '+1')}$}};")
    out += ["\\end{tikzpicture}", ""]
    return "\n".join(out)


def load_tradeoff():
    """Return {arm: cost vs causal} (seed 42, 5000 steps) from final.json or the CSV copy."""
    csv_path = DATA / "tradeoff.csv"
    arms = [arm for *_, points in TRADEOFF for arm, _ in points]

    def final(arm):
        for root in TRADEOFF_ROOTS:
            path = root / f"{arm}-s42" / "final.json"
            if path.exists():
                return json.loads(path.read_text(encoding="utf-8"))["steady_ce"]
        return None

    causal = final("causal")
    if causal is not None:
        costs = {arm: final(arm) - causal for arm in arms}
        DATA.mkdir(exist_ok=True)
        with csv_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(["arm", "cost"])
            writer.writerows([arm, f"{costs[arm]:.4f}"] for arm in arms)
        return costs
    with csv_path.open(encoding="utf-8") as f:
        return {r["arm"]: float(r["cost"]) for r in csv.DictReader(f)}


def tradeoff_figure(costs):
    """Cost vs causal against tokens per step for forward, token- and segment-reversed staggering."""
    out = [
        "% Generated by scripts/make_figures.py -- do not edit by hand.",
        "\\begin{tikzpicture}",
        "\\begin{axis}[width=0.62\\textwidth, height=5.4cm, xmin=1.4, xmax=7.35, ymin=0.24, ymax=0.6,",
        "  xtick={1.75,2.8,4,5.09,7}, xticklabels={1.75,2.8,4.0,5.09,7.0},",
        "  xlabel={tokens per step}, ylabel={cost vs.\\ causal (nats/token)},",
        "  grid=major, grid style={black!10}, axis line style={black!40}, tick style={black!40},",
        "  label style={font=\\small}, tick label style={font=\\footnotesize},",
        "  every axis plot/.append style={line width=1pt, mark size=1.8pt},",
        "  legend style={font=\\footnotesize, draw=black!20, at={(0.98,0.03)}, anchor=south east}]",
    ]
    for _, label, colour, mark, points in TRADEOFF:
        coords = " ".join(f"({x},{costs[arm]:.3f})" for arm, x in points)
        out.append(f"\\addplot[color={colour}, mark={mark}] coordinates {{{coords}}};")
        out.append(f"\\addlegendentry{{{label}}}")
    out += ["\\end{axis}", "\\end{tikzpicture}", ""]
    return "\n".join(out)


def main():
    FIGURES.mkdir(exist_ok=True)
    costs = load_tradeoff()
    (FIGURES / "tradeoff.tex").write_text(tradeoff_figure(costs), encoding="utf-8")
    print("tradeoff", {arm: round(v, 3) for arm, v in costs.items()})
    panels = {tag: load(tag) for tag in SOURCES}
    (FIGURES / "per_slot_ce.tex").write_text(per_slot_figure(panels), encoding="utf-8")
    (FIGURES / "schedule_grid.tex").write_text(schedule_figure(), encoding="utf-8")
    for tag, rows in panels.items():
        print(tag, {n: round(sum(v) / L, 3) for n, v in rows.items()})


if __name__ == "__main__":
    main()
