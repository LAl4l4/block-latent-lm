"""Write figures/examples*.tex from the sample-examples JSONs (seam.mask.examples).

Block boundaries (‖) become \\blk and judge-flagged tokens (⟦…⟧) become \\brk{…}.
The first prompts of the evaluation set are used as they are, without selection.
TinyStories' own mojibake (â€™ and similar) is written as the ASCII it stands for.

  D:\\Code\\venv313\\Scripts\\python.exe paper/reverse-staggered/scripts/make_examples.py
"""

import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent.parent
RUNS_DIR = HERE.parent.parent / "runs/schedule-mask"
OUTPUTS = {
    "examples.tex": ("sample-examples-s42-judge-s43.json",
                     [("causal-s42", "Causal"), ("forward8-s42", "Forward"),
                      ("reverse8-s42", "Reverse"), ("reverse8g8-s42", "SkipFill")]),
    "examples_parallel.tex": ("sample-examples-parallel-s42-judge-s43.json",
                              [("forward0-s42", "Forward"), ("reverse0-s42", "Reverse"),
                               ("landing-s42", "Landing")]),
}
PROMPTS = 2
SPECIAL = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&",
           "%": r"\%", "#": r"\#", "_": r"\_", "^": r"\^{}", "~": r"\~{}"}
MOJIBAKE = {"€™": "'", "€˜": "'", "€œ": '"', "€\x9d": '"', "€“": "--", "€”": "---", "â": ""}


def latex(text):
    for bad, good in MOJIBAKE.items():
        text = text.replace(bad, good)
    # A flagged "â" token whose rest of the mojibake is the next token: keep them together.
    text = re.sub(r"⟦(\s*)⟧(-{2,3}|['\"])", r"⟦\1\2⟧", text)
    if any(ord(ch) > 127 and ch not in "‖⟦⟧" for ch in text):
        raise ValueError(f"non-ASCII text needs handling: {text!r}")
    text = "".join(SPECIAL.get(ch, ch) for ch in text)
    # Samples can start or stop inside a quotation, so keep quotes straight.
    text = text.replace('"', r"\textquotedbl{}")
    text = re.sub(r"\n+", " \\\\P{} ", text)
    text = re.sub(r"⟦(\s*)(.*?)⟧", lambda m: m.group(1) + r"\brk{" + (m.group(2) or r"\P{}") + "}", text,
                  flags=re.S)
    # sample_examples joins blocks with " ‖ "; keep each block's own leading space.
    return text.replace(" ‖ ", r"\blk{}").strip()


def main():
    for name, (source, runs) in OUTPUTS.items():
        data = json.loads((RUNS_DIR / source).read_text(encoding="utf-8"))
        lines = [f"% Generated by scripts/make_examples.py from runs/schedule-mask/{source}; do not edit."]
        for i in range(PROMPTS):
            lines += [r"\par\medskip\noindent\textbf{Prompt %d.} \emph{%s}"
                      % (i + 1, latex(data["prompts"][i])),
                      r"\begin{itemize}\setlength{\itemsep}{2pt}"]
            for run, label in runs:
                lines.append(r"  \item \textsc{%s}: %s" % (label, latex(data["runs"][run]["examples"][i])))
            lines.append(r"\end{itemize}")
        (HERE / "figures" / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
        for run, label in runs:
            share = data["runs"][run]["break_share_by_slot"]
            print(label, round(data["runs"][run]["breaks_per_sample"], 1),
                  [round(100 * s) for s in share])


if __name__ == "__main__":
    main()
